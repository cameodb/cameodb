"""Builds the table behind cjk_fold into crates/storage/src/analysis/cjk/data.

    uv run --project tools/zh-fold tools/zh-fold/build.py /path/to/TSCharacters.txt

Reads OpenCC's TSCharacters.txt at the pinned commit (refused at any other checksum), takes the
first value of each entry, applies overrides.tsv, keeps the pairs whose two characters are both in
the Basic Multilingual Plane, and resolves chains so the fold is idempotent. It writes:
  fold_table.rs   KEYS and VALUES, two sorted [u16; N] arrays the runtime binary-searches
  MANIFEST.txt    the source, the commit, the overrides' sha256, the counts and the checksums
Identical inputs give identical bytes.
"""
import argparse, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'crates', 'storage', 'src', 'analysis', 'cjk', 'data')

OPENCC_COMMIT = 'fae2a0a911c30764e669a7d8b0591cd8e852934a'
SOURCE_SHA256 = '9ff46a7d30e5765375eb13d33f2b03a34d298913caf2b120380679f33ae1642d'
SOURCE_URL = (f'https://raw.githubusercontent.com/BYVoid/OpenCC/{OPENCC_COMMIT}'
              '/data/dictionary/TSCharacters.txt')
# Every key and value must fall here, so the runtime can skip any other character at once and
# rewrite a token's bytes in place: each is a 3-byte UTF-8 character.
LOW, HIGH = 0x3400, 0x9FFF


def sha256(path):
    with open(path, 'rb') as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def read_source(path):
    pairs = {}
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            if line.startswith('#') or not line.strip():
                continue
            key, values = line.rstrip('\n').split('\t')
            pairs[key] = values.split(' ')[0]
    return pairs


def read_overrides(path):
    overrides = {}
    with open(path, encoding='utf-8') as fh:
        for n, line in enumerate(fh, 1):
            if line.startswith('#') or not line.strip():
                continue
            fields = line.rstrip('\n').split('\t')
            if len(fields) != 4 or not all(fields):
                sys.exit(f'overrides.tsv:{n}: want traditional, folded, reason, reference')
            overrides[fields[0]] = fields[1]
    return overrides


def resolve(pairs):
    """Each key taken to the end of its chain, so fold(fold(c)) == fold(c); identities dropped."""
    out = {}
    for key in pairs:
        seen, value = {key}, pairs[key]
        while value in pairs and pairs[value] != value:
            if value in seen:
                sys.exit(f'cycle through {key}')
            seen.add(value)
            value = pairs[value]
        if value != key:
            out[key] = value
    return out


def rust_array(name, values):
    rows = [', '.join(f'0x{v:04X}' for v in values[i:i + 12]) for i in range(0, len(values), 12)]
    body = ''.join(f'    {row},\n' for row in rows)
    return f'pub(super) const {name}: [u16; {len(values)}] = [\n{body}];\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument('source', help=f'TSCharacters.txt, from {SOURCE_URL}')
    ap.add_argument('--overrides', default=os.path.join(HERE, 'overrides.tsv'))
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()

    digest = sha256(args.source)
    if digest != SOURCE_SHA256:
        sys.exit(f'{args.source}: sha256 {digest}, want {SOURCE_SHA256} (OpenCC {OPENCC_COMMIT})')

    source = read_source(args.source)
    first = {k: v for k, v in source.items() if k != v}
    overrides = read_overrides(args.overrides)
    merged = {**first, **overrides}
    bmp = {k: v for k, v in merged.items()
           if len(k) == 1 and len(v) == 1 and ord(k) < 0x10000 and ord(v) < 0x10000}
    table = resolve(bmp)

    for k, v in table.items():
        if not (LOW <= ord(k) <= HIGH and LOW <= ord(v) <= HIGH):
            sys.exit(f'{k}→{v} (U+{ord(k):04X}→U+{ord(v):04X}) is outside U+{LOW:04X}–U+{HIGH:04X}')
        assert table.get(v, v) == v, f'{k}→{v} is not idempotent'

    keys = sorted(table, key=ord)
    os.makedirs(args.out, exist_ok=True)
    rs = os.path.join(args.out, 'fold_table.rs')
    with open(rs, 'w', encoding='utf-8', newline='\n') as o:
        o.write('// Generated by tools/zh-fold/build.py; do not edit. See tools/zh-fold/README.md.\n')
        o.write(f'// Derived from OpenCC TSCharacters.txt (Apache-2.0, commit {OPENCC_COMMIT}),\n')
        o.write('// changed: the first value of each entry, reduced to BMP pairs, chains resolved, with the\n')
        o.write('// overrides of tools/zh-fold/overrides.tsv. Traditional characters in KEYS, each folded\n')
        o.write('// form at the same index of VALUES.\n\n')
        o.write(rust_array('KEYS', [ord(k) for k in keys]))
        o.write('\n')
        o.write(rust_array('VALUES', [ord(table[k]) for k in keys]))

    counts = {
        'entries': len(source),
        'changed by first value': len(first),
        'overrides': len(overrides),
        'overrides adding a pair': sum(1 for k in overrides if k not in first),
        'dropped outside the BMP': len(merged) - len(bmp),
        'chains resolved': sum(1 for k, v in bmp.items() if table.get(k) != v),
        'pairs': len(table),
    }
    with open(os.path.join(args.out, 'MANIFEST.txt'), 'w', encoding='utf-8', newline='\n') as o:
        o.write('# Generated by tools/zh-fold/build.py; do not edit. See tools/zh-fold/README.md.\n')
        o.write(f'source\tOpenCC data/dictionary/TSCharacters.txt (Apache-2.0) commit {OPENCC_COMMIT} '
                f'sha256 {digest}\n')
        o.write('changed\tfirst value of each entry, reduced to BMP pairs, chains resolved, with overrides\n')
        o.write(f'overrides\t{os.path.basename(args.overrides)} sha256 {sha256(args.overrides)}\n')
        o.write('counts\t' + ', '.join(f'{k} {v}' for k, v in counts.items()) + '\n')
        o.write(f'file\tfold_table.rs\t{os.path.getsize(rs)}\t{sha256(rs)}\n')
    print(', '.join(f'{k} {v}' for k, v in counts.items()))
    print(f'wrote {os.path.relpath(rs)}: {len(keys)} pairs, {4 * len(keys)} bytes of table')


if __name__ == '__main__':
    main()
